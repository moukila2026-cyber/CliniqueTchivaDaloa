"""Stockage PostgreSQL (Neon) ou SQLite pour le développement local.
Aucune connexion réseau ni création de table à l'import/build.
Les transactions, sessions, consentements et limites sont persistants côté base.
"""
import os, sqlite3, threading, json
from pathlib import Path
from contextlib import contextmanager
import psycopg
from psycopg.rows import dict_row
from psycopg.conninfo import conninfo_to_dict

INTEGRITY_ERRORS=(sqlite3.IntegrityError,psycopg.IntegrityError)
DATABASE_ERRORS=(sqlite3.DatabaseError,psycopg.Error)

class Record(dict):
    """Mapping compatible avec les accès numériques historiques SQLite."""
    def __getitem__(self,key):
        return list(self.values())[key] if isinstance(key,int) else super().__getitem__(key)

def record_factory(cursor):
    base=dict_row(cursor)
    return lambda values:Record(base(values))

class Connection:
    def __init__(self,raw,postgres):self.raw=raw;self.postgres=postgres
    def execute(self,sql,params=()):
        if self.postgres:
            if sql.strip().upper()=='BEGIN IMMEDIATE':
                # Verrou partagé entre toutes les fonctions, libéré au commit/rollback.
                # Sérialise les mutations critiques (premier compte, paiement, stock).
                return self.raw.execute('SELECT pg_advisory_xact_lock(734018211)')
            sql=sql.replace('?','%s')
        return self.raw.execute(sql,params)
    def insert_id(self,sql,params=()):
        return self.execute(sql+' RETURNING id',params).fetchone()[0]
    def executescript(self,script):
        # Schéma interne statique uniquement, jamais de texte fourni par un utilisateur.
        for statement in script.split(';'):
            if statement.strip():self.execute(statement)

class Database:
    def __init__(self):
        self.url=os.environ.get('DATABASE_URL','').strip()
        self.postgres=bool(self.url)
        self.serverless=os.environ.get('VERCEL')=='1'
        if self.serverless and not self.postgres:
            raise RuntimeError('DATABASE_URL PostgreSQL est obligatoire sur Vercel. Aucune base SQLite de secours ne sera créée.')
        if self.postgres:
            try:info=conninfo_to_dict(self.url)
            except Exception:raise RuntimeError('DATABASE_URL PostgreSQL invalide ; vérifiez sa valeur dans les variables privées.') from None
            if self.serverless and info.get('sslmode') not in {'require','verify-ca','verify-full'}:
                raise RuntimeError('La connexion PostgreSQL sur Vercel doit exiger TLS : conservez sslmode=require dans DATABASE_URL.')
            self.data=None;self.path=None
        else:
            self.data=Path(os.environ.get('DATA_DIR',Path(__file__).parent/'data'))
            self.path=self.data/'tchiva.sqlite3'
        self._ready=False;self._init_lock=threading.RLock()

    @contextmanager
    def connection(self):
        if self.postgres:
            raw=psycopg.connect(self.url,row_factory=record_factory,prepare_threshold=None,connect_timeout=10)
        else:
            self.data.mkdir(parents=True,exist_ok=True,mode=0o700)
            raw=sqlite3.connect(self.path,timeout=15);raw.row_factory=sqlite3.Row
            raw.execute('PRAGMA foreign_keys=ON');raw.execute('PRAGMA busy_timeout=15000')
        try:
            if self.postgres:
                raw.execute("SET LOCAL statement_timeout='20s'")
                raw.execute("SET LOCAL lock_timeout='10s'")
            yield Connection(raw,self.postgres)
            raw.commit()
        except:
            raw.rollback();raise
        finally:raw.close()

    def initialize(self,default):
        if self._ready:return
        with self._init_lock:
            if self._ready:return
            with self.connection() as c:
                if self.postgres:c.execute('SELECT pg_advisory_xact_lock(734018210)')
                else:c.execute('PRAGMA journal_mode=WAL')
                identity='BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' if self.postgres else 'INTEGER PRIMARY KEY'
                blob='BYTEA' if self.postgres else 'BLOB'
                real='DOUBLE PRECISION' if self.postgres else 'REAL'
                c.executescript(f'''
                CREATE TABLE IF NOT EXISTS settings(id INTEGER PRIMARY KEY CHECK(id=1), data TEXT NOT NULL);
                CREATE TABLE IF NOT EXISTS users(id {identity}, name TEXT NOT NULL, email TEXT UNIQUE NOT NULL, password {blob} NOT NULL, role TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 1);
                CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), csrf TEXT NOT NULL, expires {real} NOT NULL);
                CREATE TABLE IF NOT EXISTS appointments(id {identity}, reference TEXT UNIQUE NOT NULL, patient TEXT NOT NULL, phone TEXT NOT NULL, service TEXT NOT NULL, practitioner TEXT NOT NULL DEFAULT '', day TEXT NOT NULL, slot TEXT NOT NULL, consent INTEGER NOT NULL, privacy_at TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending', created_at TEXT NOT NULL);
                CREATE UNIQUE INDEX IF NOT EXISTS confirmed_slot ON appointments(day,slot,practitioner) WHERE status='confirmed' AND slot!='';
                CREATE TABLE IF NOT EXISTS consultations(id {identity}, patient TEXT NOT NULL, service TEXT NOT NULL, practitioner TEXT NOT NULL, day TEXT NOT NULL, amount BIGINT NOT NULL, paid BIGINT NOT NULL, appointment_id BIGINT UNIQUE REFERENCES appointments(id), created_at TEXT NOT NULL);
                CREATE TABLE IF NOT EXISTS transactions(id {identity}, kind TEXT NOT NULL, category TEXT NOT NULL, label TEXT NOT NULL, amount BIGINT NOT NULL CHECK(amount>0), day TEXT NOT NULL, consultation_id BIGINT UNIQUE REFERENCES consultations(id), created_at TEXT NOT NULL);
                CREATE TABLE IF NOT EXISTS inventory(id {identity}, name TEXT UNIQUE NOT NULL, unit TEXT NOT NULL, quantity BIGINT NOT NULL CHECK(quantity>=0), threshold BIGINT NOT NULL CHECK(threshold>=0));
                CREATE TABLE IF NOT EXISTS movements(id {identity}, item_id BIGINT REFERENCES inventory(id), delta BIGINT NOT NULL, reason TEXT NOT NULL, created_at TEXT NOT NULL);
                CREATE TABLE IF NOT EXISTS audit(id {identity}, user_id BIGINT, action TEXT NOT NULL, entity TEXT NOT NULL, created_at TEXT NOT NULL);
                CREATE TABLE IF NOT EXISTS rate_limits(key TEXT NOT NULL, bucket BIGINT NOT NULL, count BIGINT NOT NULL, expires {real} NOT NULL, PRIMARY KEY(key,bucket));
                CREATE INDEX IF NOT EXISTS rate_expiry ON rate_limits(expires);
                CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires);
                CREATE INDEX IF NOT EXISTS appointment_day ON appointments(day,status);
                CREATE INDEX IF NOT EXISTS transaction_day ON transactions(day);
                ''')
                c.execute('INSERT INTO settings(id,data) VALUES(1,?) ON CONFLICT(id) DO NOTHING',(json.dumps(default,ensure_ascii=False),))
            if not self.postgres:os.chmod(self.path,0o600)
            self._ready=True
